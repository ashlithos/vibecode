#!/usr/bin/env python3
"""Inline src/core.css + src/core.js + src/games/<name>.js into prototypes/<name>.html.

Every output file is a single self-contained page: no CDNs, no external fonts, works offline.
Run:  python3 build.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).parent
SRC = ROOT / "src"
OUT = ROOT / "prototypes"

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
{css}
</style>
</head>
<body>
<!--
  {title}: single-file playtest prototype (generated by build.py; edit src/ instead).
  REAL API PLUG-IN POINT: every AI result is a placeholder card made by Core.genCard() and
  revealed by Core.generate(). To go live, replace Core.generate() with a call to a real
  image / video / audio API using the prompt shown on the card.
-->
<noscript>This prototype needs JavaScript enabled.</noscript>
<script>
{core}
</script>
<script>
{game}
</script>
</body>
</html>
"""


def main():
    OUT.mkdir(exist_ok=True)
    css = (SRC / "core.css").read_text()
    core = (SRC / "core.js").read_text()
    built = []
    for game in sorted((SRC / "games").glob("*.js")):
        text = game.read_text()
        m = re.search(r"^// TITLE: (.+)$", text, re.M)
        title = m.group(1).strip() if m else game.stem
        html = TEMPLATE.format(title=title, css=css, core=core, game=text)
        (OUT / f"{game.stem}.html").write_text(html)
        built.append(game.stem)
    (OUT / "index.html").write_text((SRC / "index.html").read_text())
    print(f"Built {len(built)} prototypes + index.html:", *built, sep="\n  ")


if __name__ == "__main__":
    main()
